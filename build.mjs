// Build the fixed local module graph into a classic script and a single HTML.
// No npm installation or network access is required.
import { readFile, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';
const read = path => readFile(new URL(path, import.meta.url), 'utf8');
const modules = [
  ['THREE', 'dist/vendor/three.module.js'],
  ['rhythmAnalysis', 'dist/js/rhythm-analysis.js'],
  ['rhythmClock', 'dist/js/rhythm-clock.js'],
  ['analysis', 'dist/js/audio-analysis.js'],
  ['player', 'dist/js/audio-player.js'],
  ['shapes', 'dist/js/shapes.js'],
  ['kaleidoShaders', 'dist/js/kaleido-shaders.js'],
  ['kaleidoWorlds', 'dist/js/kaleido-worlds.js'],
  ['kaleidoscope', 'dist/js/kaleidoscope.js'],
  ['atmosphere', 'dist/js/atmosphere.js'],
  ['artist', 'dist/js/artist.js'],
  ['director', 'dist/js/director.js'],
  ['recorder', 'dist/js/show-recorder.js'],
  ['visualizer', 'dist/js/visualizer.js'],
  ['app', 'dist/js/app.js'],
];
const dependencies = {
  '../vendor/three.module.js': 'THREE', './audio-analysis.js': 'analysis',
  './audio-player.js': 'player', './shapes.js': 'shapes', './visualizer.js': 'visualizer',
  './rhythm-analysis.js': 'rhythmAnalysis', './rhythm-clock.js': 'rhythmClock',
  './kaleidoscope.js': 'kaleidoscope', './atmosphere.js': 'atmosphere',
  './kaleido-shaders.js': 'kaleidoShaders',
  './kaleido-worlds.js': 'kaleidoWorlds',
  './artist.js': 'artist', './director.js': 'director', './show-recorder.js': 'recorder',
};
let bundle = '// Generated by build.mjs. Edit the source modules, then rebuild.\n(() => {\n"use strict";\n';
for (const [id, path] of modules) {
  let source = await read(path);
  const exports = [];
  source = source.replace(/^import\s+(.+?)\s+from\s+['"](.+?)['"];?\s*$/gm, (_, binding, specifier) => {
    const dependency = dependencies[specifier];
    if (!dependency) throw new Error(`Unknown dependency: ${specifier}`);
    return binding.startsWith('* as ')
      ? `const ${binding.slice(5)} = modules.${dependency};`
      : `const ${binding} = modules.${dependency};`;
  });
  source = source.replace(/^export\s*\{([^}]+)\};?\s*$/gm, (_, names) => {
    exports.push(...names.split(',').map(name => name.trim().replace(/^(\w+)\s+as\s+(\w+)$/, '$2: $1')));
    return '';
  });
  source = source.replace(/\bexport\s+(class|(?:async\s+)?function|const|let)\s+(\w+)/g, (_, kind, name) => {
    exports.push(name);
    return `${kind} ${name}`;
  });
  if (/^\s*(import|export)\s/m.test(source)) throw new Error(`Unconverted module statement: ${path}`);
  bundle += `modules.${id} = (() => {\n${source}\nreturn { ${exports.join(', ')} };\n})();\n`;
}
bundle = bundle.replace('"use strict";\n', '"use strict";\nconst modules = {};\n') + '})();\n';
new Script(bundle, { filename: 'app.bundle.js' });
await writeFile(new URL('dist/js/app.bundle.js', import.meta.url), bundle);
const css = await read('dist/style.css');
const meyda = await read('dist/vendor/meyda.min.js');
const scriptText = source => source.replace(/<\/script/gi, '<\\/script');
let html = await read('dist/index.html');
html = html.replace('<link rel="stylesheet" href="./style.css">', () => `<style>\n${css}\n</style>`)
  .replace('  <script defer src="./vendor/meyda.min.js"></script>\n', '')
  .replace('  <script defer src="./js/app.bundle.js"></script>\n', '')
  .replace('href="./"', 'href="#"')
  .replace('</body>', () => `<script>\n${scriptText(meyda)}\n</script>\n<script>\n${scriptText(bundle)}\n</script>\n</body>`);
await writeFile(new URL('Музыкальный калейдоскоп.html', import.meta.url), html);
console.log('Built dist/js/app.bundle.js and Музыкальный калейдоскоп.html');
